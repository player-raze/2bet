export const useSiteLocale = () => {
  const localeCookie = useCookie<LocaleCode>(LANGUAGE_SESSION_KEY, {
    default: () => DEFAULT_LOCALE,
    sameSite: 'lax',
  })
  const locale = useState<LocaleCode>('2bet-locale', () => {
    return isLocaleCode(localeCookie.value) ? localeCookie.value : DEFAULT_LOCALE
  })

  const selectedLanguageLabel = computed(() => {
    return languageOptions.find(option => option.code === locale.value)?.label ?? 'Português'
  })

  const translate = (sourceText: string): string => {
    return homepageFooterTranslations[locale.value]?.[sourceText]
      ?? newContentTranslations[locale.value]?.[sourceText]
      ?? contentTranslations[locale.value]?.[sourceText]
      ?? translations[locale.value]?.[sourceText]
      ?? sourceText
  }

  const setLocale = (nextLocale: LocaleCode): void => {
    locale.value = nextLocale
    localeCookie.value = nextLocale

    if (import.meta.client) {
      document.documentElement.lang = nextLocale
      window.sessionStorage.setItem(LANGUAGE_SESSION_KEY, nextLocale)
      window.localStorage.setItem(LANGUAGE_SESSION_KEY, nextLocale)
    }
  }

  const restoreLocale = (): void => {
    if (!import.meta.client) {
      return
    }

    const savedLocale = window.sessionStorage.getItem(LANGUAGE_SESSION_KEY)
      || window.localStorage.getItem(LANGUAGE_SESSION_KEY)
      || window.localStorage.getItem('bybet-language')
    const nextLocale = isLocaleCode(savedLocale)
      ? savedLocale
      : isLocaleCode(localeCookie.value) ? localeCookie.value : DEFAULT_LOCALE

    locale.value = nextLocale
    localeCookie.value = nextLocale
    document.documentElement.lang = nextLocale
  }

  return {
    locale,
    restoreLocale,
    selectedLanguageLabel,
    setLocale,
    translate,
  }
}

export const useSitePreferences = useSiteLocale

export const useSiteTheme = () => {
  const themeCookie = useCookie<ThemePreference>('2bet-theme', {
    default: () => DEFAULT_THEME_PREFERENCE,
    sameSite: 'lax',
    maxAge: 60 * 60 * 24 * 365,
  })
  const themePreference = useState<ThemePreference>('2bet-theme-preference', () => {
    return isThemePreference(themeCookie.value) ? themeCookie.value : DEFAULT_THEME_PREFERENCE
  })
  const effectiveTheme = useState<EffectiveTheme>('2bet-effective-theme', () => {
    return themePreference.value === 'light' ? 'light' : 'dark'
  })

  const applyTheme = (): void => {
    if (!import.meta.client) {
      return
    }

    effectiveTheme.value = themePreference.value === 'auto'
      ? window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light'
      : themePreference.value

    document.documentElement.dataset.theme = effectiveTheme.value
    document.documentElement.dataset.themePreference = themePreference.value
  }

  const setThemePreference = (nextPreference: ThemePreference): void => {
    themePreference.value = nextPreference
    themeCookie.value = nextPreference

    if (import.meta.client) {
      window.localStorage.setItem('2bet-theme', nextPreference)
    }

    applyTheme()
  }

  return {
    applyTheme,
    effectiveTheme,
    setThemePreference,
    themePreference,
  }
}
